# 基本情報（固定の各種手当）（実際の金額に変更してください）
基本給 = 200000
家族手当 = 30000
無事故手当 = 10000
通信費手当 = 1000

# 手当単価
深夜手当単価 = 334 # 実際の単価に変更してください
残業手当単価 = 1670 # 実際の単価に変更してください

# ルート手当の一覧（実際のルート名と金額に変更してください）
ルート手当 = {
    "ルートA": 500,
    "ルートB": 600,
    "ルートC": 1200,
    "なし": 0
}

# 深夜・残業時間を入力
print("=== それぞれ時間を入力してください ===")
深夜時間_時 = int(input("深夜時間（時）:"))
深夜時間_分 = int(input("深夜時間（分）:"))
残業時間_時 = int(input("残業時間（時）:"))
残業時間_分 = int(input("残業時間（分）:"))

# ルートと日数を入力
print("=== ルートと日数を入力してください ===")
print("ルート一覧：ルートA / ルートB / ルートC / なし")

今月のルート = []
while True:
    ルート = input("ルート名（終了する場合はEnterだけ押してください）:")
    if ルート == "":
        break
    if ルート not in ルート手当:
        print("そのルートは存在しません。もう一度入力してください。")
        continue
    日数 = int(input("日数:"))
    今月のルート.append((ルート, 日数))

# 分を時間に変換
深夜時間 = 深夜時間_時 + 深夜時間_分 / 60
残業時間 = 残業時間_時 + 残業時間_分 / 60

# 深夜・残業手当計算（実際の時間給に変更してください）
深夜手当 = 深夜時間 * 深夜手当単価
残業手当 = 残業時間 * 残業手当単価

# ルート手当計算
ルート手当合計 = 0
for ルート, 日数 in 今月のルート:
    ルート手当合計 += ルート手当[ルート] * 日数

# 合計
合計 = 基本給 + 家族手当 + 無事故手当 + 通信費手当 + 深夜手当 + 残業手当 + ルート手当合計

# 結果をファイルに保存
import datetime
今月 = datetime.datetime.now().strftime("%Y年%m月")

with open("給与記録.txt", "a") as f:
    f.write("=== " + 今月 + "の給与計算結果 ===\n")
    f.write("基本給:" + str(基本給) + "円\n")
    f.write("家族手当:" + str(round(家族手当)) + "円\n")
    f.write("無事故手当:" + str(round(無事故手当)) + "円\n")
    f.write("通信費手当:" + str(round(通信費手当)) + "円\n")
    f.write("深夜手当:" + str(round(深夜手当)) + "円\n")
    f.write("残業手当:" + str(round(残業手当)) + "円\n")
    f.write("ルート手当合計:" + str(ルート手当合計) + "円\n")
    f.write("合計:" + str(round(合計)) + "円\n")
    f.write("\n")

print("給与記録.txtに保存しました！")

print("=== 給与計算結果 ===")
print("基本給:" + str(基本給) + "円")
print("家族手当:" + str(round(家族手当)) + "円")
print("無事故手当:" + str(round(無事故手当)) + "円")
